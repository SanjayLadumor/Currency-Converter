const Base_Url = "https://cdn.jsdelivr.net/npm/@fawazahmed0/currency-api@latest/v1/currencies";

const dropdownselect = document.querySelectorAll(".select-container select")

const msg = document.querySelector(".conversion")

const btn = document.querySelector(".exbutton button")

for (let select of dropdownselect) {
    for (currcode in countryList) {
        let newopt = document.createElement("option")
        newopt.innerText = currcode
        newopt.value = currcode
        if (select.name === "from" && currcode === "USD") {
            newopt.selected = "selected"
        }
        else if (select.name === "to" && currcode === "INR") {
            newopt.selected = "selected"
        }
        select.append(newopt);
    }

    select.addEventListener("change", (evt) => {
        updateflag(evt.target);
    })
}

const updateflag = (element) => {
    let currcode = element.value;
    let countrycode = countryList[currcode];
    let newsrc = `https://flagsapi.com/${countrycode}/flat/64.png`;
    element.parentElement.querySelector("img").src = newsrc;
}

btn.addEventListener("click",() => {
    logic();
})

const logic = async() => {
    let amount = document.querySelector(".amount input")
    let amtval = amount.value;
    if (amtval === "" || amtval < 1) {
        amtval = 1;
        amount.value = 1;
    }

    let fromv = document.querySelector(".from .select-container select");
    let fromval = fromv.value.toLowerCase();

    let tov = document.querySelector(".to .select-container select");
    let toval = tov.value.toLowerCase();

    const URL = `${Base_Url}/${fromval}.json`;

    let response = await fetch(URL);
    let data = await response.json();
    let rate = data[fromval][toval];
    let finalamount = rate * amtval;
    msg.innerText = `${amtval} ${fromv.value} = ${finalamount} ${tov.value}`
}

window.addEventListener("load", () => {
    logic();
})
